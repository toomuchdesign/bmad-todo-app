import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webDir = path.resolve(scriptDir, "..");
const openapiPath = path.resolve(webDir, "..", "api", "openapi.json");
const outDir = path.resolve(webDir, "src", "api", "generated");
const outFile = path.resolve(outDir, "index.ts");

const openapiRaw = await fs.readFile(openapiPath, "utf8");
const openapi = JSON.parse(openapiRaw);

const paths = Object.keys(openapi.paths ?? {});

await fs.mkdir(outDir, { recursive: true });
await fs.writeFile(
  outFile,
  `// GENERATED FILE - do not edit\n` +
    `// Generated by: npm -w src/web run build:api-types\n\n` +
    `export const apiPaths = ${JSON.stringify(paths)} as const;\n` +
    `export type ApiPath = (typeof apiPaths)[number];\n`,
  "utf8",
);
